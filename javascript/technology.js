function showTechnology(name) {

    if (name === "Automatic Movement") {

        alert("Automatic watches are powered by the natural movement of your wrist.");

    }

    else if (name === "Quartz Technology") {

        alert("Quartz watches use battery-powered quartz technology for accurate timekeeping.");

    }

    else if (name === "Eco-Drive Technology") {

        alert("Eco-Drive technology converts light into energy and reduces the need for regular battery changes.");

    }

    else if (name === "Smart Watch Technology") {

        alert("Smart watches provide digital features, connectivity and modern convenience.");

    }

}